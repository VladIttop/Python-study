#Arithmetic operator plus (+) is used to add two numbers together. In this example, we are adding 1 to the variable friends and then printing the result.
friends = 0
friends = friends + 1
print(friends)
print("-----------------------------------")
#Arithmetic operator minus (-) is used to subtract one number from another. In this example, we are subtracting 2 from the variable friends and then printing the result.
friends -= 2
print(friends)
print("-----------------------------------")
#Multiplication operator (*) is used to multiply two numbers together. In this example, we are multiplying the variable friends by 3 and then printing the result.
friends *= 3
print(friends)
print("-----------------------------------")
#Division operator (/) is used to divide one number by another. In this example, we are dividing the variable friends by 2 and then printing the result.
friends /= 2
print(friends)
print("-----------------------------------")
#Exponentiation operator (**) is used to raise a number to the power of another number. In this example, we are raising the variable friends to the power of 2 and then printing the result.
friends **= 2
print(friends)
print("-----------------------------------")
#Modulus operator (%) is used to find the remainder of a division operation. In this example, we are finding the remainder when the variable friends is divided by 2 and then printing the result.
friends %= 2
print(friends)
print("-----------------------------------")
#Floor division operator (//) is used to divide one number by another and return the integer part of the result. In this example, we are dividing the variable friends by 2 and then printing the result.
friends //= 2
print(friends)
print("-----------------------------------")