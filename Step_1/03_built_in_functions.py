#Built-in Functions
x = 3.14
y = 4
z = 5

result = round(x)
print("Rounded value of x:", result)

print("-----------------------------------")
#absolute value 
print("Absolute value of y:", abs(y))
print("-----------------------------------")
#power function
result = pow(y, z)
print("y raised to the power of z:", result)
print("-----------------------------------")
#max function
result = max(x, y, z)
print("Maximum value among x, y, and z:", result)
print("-----------------------------------")
#min function
result = min(x, y, z)
print("Minimum value among x, y, and z:", result)